"use client";

import CustomInput from "@/components/reusable/dashboard/CustomInput";
import { useProviderEmailCodeMutation } from "@/feature/slice/admin/securitySettings";
import { useState } from "react";
import toast from "react-hot-toast";

interface StepEmailCodeProps {
  onSuccess: (codes: string[]) => void;
  onBack: () => void;
  onClose: () => void;
}

export default function StepEmailCode({
  onSuccess,
  onBack,
  onClose,
}: StepEmailCodeProps) {
  const [code, setCode] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

   const [providerEmailCode] = useProviderEmailCodeMutation();

  const handleSubmit = async (e: React.FormEvent) => {
  e.preventDefault();
  setError("");
  setLoading(true);

  const payload = {
    code: code,
  };

 try {
  const response = await providerEmailCode(payload).unwrap();

  if (response.status) {
    toast.success(response.message || "Code verified successfully");
    const codes =
      response.recovery_codes ||
      response.backup_codes ||
      response.data?.recovery_codes ||
      response.data?.backup_codes ||
      [];
    onSuccess(codes);
  } else {
    setError(response.message || "Failed to verify code");
  }
} catch (error: any) {
    const errorMessage =
      error?.data?.message || "An error occurred. Please try again.";
    setError(errorMessage);
  } finally {
    setLoading(false);
  }
};
  return (
    <form onSubmit={handleSubmit} className="space-y-4 px-3">
      <p className="text-sm text-[#777980]">
       Enter the 6-digit code generated by your Authenticator app

      </p>

       <p className="text-sm text-[#777980]">
        <p className="text-sm text-[#777980]">
     Note: You can also copy the code by tapping on it and pasting into the LinkedIn app


      </p>

      </p>

      <CustomInput
       
        type="text"
        required
        value={code}
        onChange={(e) => setCode(e.target.value)}
        placeholder="Enter 6-digit code"
        maxLength={6}
        error={error}
        className="text-center tracking-widest text-lg"
      />

      {/* <button type="button" className="text-sm font-medium text-primaryColor">
        Resend Code
      </button> */}

      <div className="flex flex-col-reverse  gap-3 pt-2">
     
        <button
          type="button"
          onClick={onBack}
          className="rounded-md border px-4 py-2 text-sm font-medium"
        >
          Back to Setup
        </button>
             <button
          type="submit"
          disabled={loading}
          className="rounded-md bg-primaryColor px-4 py-2 text-sm font-medium text-white disabled:opacity-60"
        >
          {loading ? "Confirming..." : "Confirm"}
        </button>
      
      </div>
    </form>
  );
}